// Renders a reference sheet PNG for every Latch & Friends character plus a roster sheet, from characters.mjs
// and the generated emotes. Needs Playwright (preinstalled in dev containers).
//   node scripts/site/emotes/make-sheets.mjs <outDir>
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join, resolve } from "node:path";
import { CHARACTERS, EMOTES } from "./characters.mjs";

const require = createRequire(import.meta.url);
const { chromium } = require("playwright");
const out = resolve(process.argv[2] || "tmp/reference-sheets");
mkdirSync(out, { recursive: true });
const A = resolve("public/site/assets"), E = resolve("public/site/img/pass/emotes");
const fonts = `@font-face{font-family:O;src:url(file://${A}/cardbit-outfit-800-latin.woff2)}@font-face{font-family:K;src:url(file://${A}/cardbit-type-atkinson.woff)}`;
const css = `${fonts}*{box-sizing:border-box}body{margin:0;background:#0b1517;color:#e8f4f3;font:17px/1.45 K,system-ui}
h1,h2,h3{font-family:O;margin:0}.sw{display:flex;gap:10px}.sw div{width:84px}.sw i{display:block;height:44px;border-radius:10px;border:1px solid #ffffff22}.sw small{font-size:12px;color:#a8b3c7}
ul{margin:0;padding-left:20px}.dim{color:#a8b3c7}`;
const inline = (f) => readFileSync(f, "utf8").replace('width="256" height="256"', 'width="100%" height="100%"');
const baseIcon = (c) => c.raster ? `<img src="file://${A}/${c.base}" style="width:100%;border-radius:50%">` : inline(join(A, c.base));

function sheet(c) {
  const em = EMOTES.map((e) => `<figure style="margin:0;text-align:center"><div style="width:190px;height:190px">${inline(join(E, `${c.id}-${e.id}.svg`)).replace(/id="([^"]+)"/g, `id="$1-${e.id}"`).replace(/url\(#([^)]+)\)/g, `url(#$1-${e.id})`)}</div>
<figcaption style="font-family:O;margin-top:6px">${e.name}${e.ultimate ? ' <span style="color:#FFC94D">(Ultimate)</span>' : ""}</figcaption></figure>`).join("");
  return `<!doctype html><meta charset="utf-8"><style>${css}</style><body style="width:1400px;padding:44px">
<div style="display:flex;gap:44px;align-items:flex-start">
<div style="width:360px;flex:none"><div style="width:360px;height:360px">${baseIcon(c)}</div>
<p class="dim" style="margin:10px 0 0;text-align:center">Approved starter icon (the master)</p></div>
<div style="display:grid;gap:18px;min-width:0">
<div><p class="dim" style="margin:0;letter-spacing:.12em;text-transform:uppercase;font-size:13px">Latch &amp; Friends reference sheet</p>
<h1 style="font-size:58px;color:${c.colors.rim}">${c.name}</h1><p style="margin:2px 0 0;font-size:19px"><b>Element:</b> ${c.element[0].toUpperCase() + c.element.slice(1)} &nbsp;·&nbsp; <b>Effects:</b> ${c.fx}</p></div>
<p style="margin:0">${c.body}</p>
<p style="margin:0"><b>Personality:</b> ${c.personality}</p>
<div><h3 style="margin-bottom:6px">Always Keep</h3><ul>${c.traits.map((t) => `<li>${t}</li>`).join("")}<li>Near-black screen face with white glyph eyes and mouth</li><li>Neon rim glow in the rim color, same thickness in every pose</li></ul></div>
<div class="sw">${Object.entries(c.colors).map(([k, v]) => `<div><i style="background:${v}"></i><small>${k}<br>${v}</small></div>`).join("")}</div>
</div></div>
<h2 style="margin:34px 0 14px">Expressions (Pack Pass emotes)</h2>
<div style="display:flex;gap:22px">${em}</div>
<p class="dim" style="margin-top:22px;font-size:14px">Every emote reuses the master body unchanged; only the face glyphs, motion and ${c.fx.toLowerCase()} change. Generated by scripts/site/emotes from characters.mjs.</p>
</body>`;
}
function roster() {
  return `<!doctype html><meta charset="utf-8"><style>${css}</style><body style="width:1400px;padding:44px">
<h1 style="font-size:46px;margin-bottom:6px">Latch &amp; Friends: Character Roster</h1><p class="dim" style="margin:0 0 26px">12 characters. Each has 4 Pack Pass emotes (Hype, Love, LOL, Shocked) plus a Legendary emote for Ultimate.</p>
<div style="display:grid;grid-template-columns:repeat(6,1fr);gap:22px">${CHARACTERS.map((c) => `<figure style="margin:0;text-align:center"><div style="width:190px;height:190px;margin:auto">${baseIcon(c)}</div>
<figcaption><b style="font-family:O;font-size:20px;color:${c.colors.rim}">${c.name}</b><br><span class="dim">${c.element[0].toUpperCase() + c.element.slice(1)}</span></figcaption></figure>`).join("")}</div></body>`;
}

const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1400, height: 900 }, deviceScaleFactor: 1 });
async function shot(html, name) {
  const f = join(out, name + ".html");
  writeFileSync(f, html);
  await p.goto("file://" + f);
  await p.waitForTimeout(400);
  await p.evaluate(() => document.getAnimations().forEach((a) => { a.pause(); a.currentTime = 600; }));
  await p.screenshot({ path: join(out, name + ".png"), fullPage: true });
}
await shot(roster(), "00-roster");
for (const [i, c] of CHARACTERS.entries()) await shot(sheet(c), `${String(i + 1).padStart(2, "0")}-${c.id}`);
await b.close();
console.log("sheets in " + out);
